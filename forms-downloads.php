  <script>
    document.addEventListener('DOMContentLoaded', () => {
      const cards = document.querySelectorAll('.form-download-card');
      const pdfjs = window.pdfjsLib;

      if (pdfjs) {
        pdfjs.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';
      }

      const showPlaceholder = (preview, message) => {
        preview.innerHTML = `
          <div class="pdf-preview-placeholder">
            <i class="bi bi-file-earmark-pdf"></i>
            <span>${message}</span>
          </div>
        `;
      };

      const renderPdfPreview = async (preview, pdfUrl) => {
        if (!pdfjs) {
          showPlaceholder(preview, 'PDF preview library could not load.');
          return;
        }

        try {
          const pdf = await pdfjs.getDocument(pdfUrl).promise;
          const page = await pdf.getPage(1);
          const viewport = page.getViewport({ scale: 1.25 });
          const canvas = document.createElement('canvas');
          const context = canvas.getContext('2d');
          canvas.width = viewport.width;
          canvas.height = viewport.height;
          preview.innerHTML = '';
          preview.appendChild(canvas);
          await page.render({ canvasContext: context, viewport }).promise;
        } catch (error) {
          showPlaceholder(preview, 'PDF preview will appear here once a valid PDF link is added.');
        }
      };

      cards.forEach((card) => {
        const link = card.querySelector('.form-download-btn');
        const pdfUrl = card.dataset.pdf || (link && link.href.toLowerCase().includes('.pdf') ? link.getAttribute('href') : '');
        const preview = document.createElement('div');
        preview.className = 'pdf-preview';
        card.prepend(preview);

        if (pdfUrl) {
          renderPdfPreview(preview, pdfUrl);
        } else {
          showPlaceholder(preview, 'PDF unavailable at the moment');
        }
      });
    });
  </script>

